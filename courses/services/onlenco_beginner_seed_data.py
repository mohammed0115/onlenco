# Final integrity check at import time — keeps a typo from shipping.
def _validate_units() -> None:
    seen = set()
    for u in UNITS:
        assert u["n"] not in seen, f"Duplicate unit number: {u['n']}"
        seen.add(u["n"])
        assert 1 <= u["n"] <= 48
        assert u["cefr"] in ("A0", "A1")
        assert u["review_group"] in ("R1", "R2", "R3", "R4", "R5", "R6")
    assert seen == set(range(1, 49)), f"Missing units: {set(range(1, 49)) - seen}"


_validate_units()
