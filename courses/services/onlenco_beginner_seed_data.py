def _h(s: str) -> str:
    """HTML-escape a piece of inline text."""
    return escape(s or "", quote=True)


def build_content_html(unit: dict) -> str:
    """Produce the 12-section English content for a Lesson's content_html."""
    examples_html = "".join(
        f"<li><strong>{_h(en)}</strong> — <em>{_h(ar)}</em></li>"
        for en, ar in unit.get("examples", [])
    ) or "<li><em>(populated in P12)</em></li>"

    dialogue_html = "".join(
        f"<li><strong>{_h(speaker)}:</strong> {_h(line)}</li>"
        for speaker, line in unit.get("dialogue", [])
    ) or "<li><em>(populated in P12)</em></li>"

    checklist_html = "".join(
        f"<li>{_h(en)}</li>"
        for en, _ar in unit.get("checklist", [])
    ) or "<li><em>(populated)</em></li>"

    return (
        f"<h3>1. Lesson Goal</h3><p>{_h(unit['skill_en'])}</p>"
        f"<h3>2. New Language</h3><p>{_h(unit['new_language_en'])}</p>"
        f"<h3>3. Key Vocabulary</h3><p>{_h(unit['vocabulary_en'])}</p>"
        f"<h3>4. Grammar Focus</h3><p>{_h(unit['grammar_en'])}</p>"
        f"<h3>5. Visual Guide</h3><p><em>{_h(unit['image_idea'])}</em></p>"
        f"<h3>6. Examples</h3><ul>{examples_html}</ul>"
        f"<h3>7. Mini Dialogue</h3><ul>{dialogue_html}</ul>"
        f"<h3>8. Practice Activity</h3><p>{_h(unit['quiz_goal_en'])}</p>"
        f"<h3>9. Listening Task</h3><p>{_h(unit['listening_goal_en'])}</p>"
        f"<h3>10. Speaking Practice</h3><p>{_h(unit['speaking_goal_en'])}</p>"
        f"<h3>11. AI Tutor Drill</h3><p>{_h(unit['ai_tutor_goal_en'])}</p>"
        f"<h3>12. Checklist</h3><ul>{checklist_html}</ul>"
    )


